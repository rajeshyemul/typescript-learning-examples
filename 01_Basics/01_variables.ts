// --------------------------------------------------
// JavaScript example
// --------------------------------------------------

// Declaring variables in JavaScript
// JavaScript is dynamically typed

var num1 = 10;                         // Number type
var role = "Test Automation Engineer"; // String type
var isArchitect = true;                // Boolean type

// JavaScript allows reassignment to different types
// num1 = "ten";   // This is allowed in JavaScript

console.log("num1:", num1);
console.log("role:", role);
console.log("isArchitect:", isArchitect);

// --------------------------------------------------
// TypeScript example
// --------------------------------------------------

// Declaring variables with explicit types
// TypeScript is statically typed

let tsNum1: number = 10;
let tsRole: string = "Test Automation Engineer";
let tsIsArchitect: boolean = true;

// TypeScript prevents type reassignment
// tsNum1 = "ten"; // ❌ Compile-time error

console.log("tsNum1:", tsNum1);
console.log("tsRole:", tsRole);
console.log("tsIsArchitect:", tsIsArchitect);

/*
========================
Key Learning Points
========================
*/

// 1. Java requires explicit types for all variables.
// 2. JavaScript determines types at runtime (dynamic typing).
// 3. JavaScript allows variables to change types, which can cause bugs.
// 4. TypeScript adds static typing on top of JavaScript.
// 5. TypeScript catches type errors at compile time.
// 6. let is preferred over var in modern JavaScript and TypeScript.
// 7. Clear typing improves readability and maintainability.
